-- CourseIQ PostgreSQL Schema (Tier 3: Centralized Data Storage Subsystem)

CREATE TABLE IF NOT EXISTS public.courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    department TEXT NOT NULL,
    professor TEXT NOT NULL,
    difficulty NUMERIC(3,1),
    workload NUMERIC(4,1),
    reviews INTEGER NOT NULL DEFAULT 0,
    description TEXT,
    meeting_times TEXT
);

CREATE TABLE IF NOT EXISTS public.course_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    difficulty_rating INTEGER NOT NULL CHECK (difficulty_rating BETWEEN 1 AND 5),
    weekly_workload_hours NUMERIC(4,1) NOT NULL CHECK (weekly_workload_hours >= 0),
    written_feedback TEXT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);